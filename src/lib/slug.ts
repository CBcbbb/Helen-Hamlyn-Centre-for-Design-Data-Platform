/**
 * Turn a display name into a URL slug.
 * "DOME: Design Out Medical Error" → "dome-design-out-medical-error"
 * "i~design Programme" → "i-design-programme"
 */
export function slugify(name: string): string {
  return name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80)
    .replace(/-+$/g, '');
}
